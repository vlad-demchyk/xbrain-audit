def _pages_section(model: ReportModel, labels: dict) -> str:
    """What was examined, as a compact table rather than a numbered list.

    A crawl of 192 pages produced 192 numbered lines in 10.5pt type, several
    printed pages of index before the first finding. It is context, not
    content: it belongs in small type, sorted so the pages carrying the most
    problems come first, and cut off once it stops informing.
    """
    if not model.pages:
        return ""
    pages = sorted(model.pages,
                   key=lambda p: -(p.get("findings_count") or 0))
    rows = "".join(
        f'<tr><td>{_esc(p.get("source", ""))}</td>'
        f'<td class="num">{p.get("findings_count", 0)}</td></tr>'
        for p in pages[:_PAGES_SHOWN])
    extra = len(pages) - _PAGES_SHOWN
    if extra > 0:
        rows += (f'<tr class="more"><td colspan="2">'
                 f'{_esc(labels["pages_more"].format(count=extra))}</td></tr>')
    return (f'<section class="pages"><h2>{_esc(labels["pages_examined"])} '
            f'({len(pages)})</h2>'
            f'<table class="category-table pages-table">'
            f'<tr><th>{_esc(labels["page_col"])}</th>'
            f'<th class="num">{_esc(labels["count"])}</th></tr>'
            f'{rows}</table></section>')


def _top_patterns_section(model: ReportModel, labels: dict, lang="en") -> str:
    """The highest-scoring passages, kept as detail rather than as a summary.

    The confidence tally that used to head this section now lives in the one
    "what was found" table; what is left here is the part that cannot go in a
    tally - the actual text, and why it scored.
    """
    ai = model.ai_patterns or {}
    top = ai.get("top_patterns") or []
    if not top:
        return ""
    rows = []
    for p in top:
        explanation = _esc(p.get("explanation", ""))
        # A repo path is not a fifth column - most reports have none to show,
        # and a column empty in every row but a few reads as a layout defect
        # rather than as "this one is different". It rides inside the
        # explanation cell instead, on its own line, only where it exists.
        if p.get("source_file"):
            note = labels["source_at"].format(
                path=p["source_file"], line=p.get("source_line", 0))
            explanation += f'<div class="src">{_esc(note)}</div>'
        if p.get("mapping", {}).get("status") in ("ambiguous", "inferred"):
            from repo_pairing import mapping_lines
            for note in mapping_lines(p["mapping"], lang):
                explanation += f'<div class="src">{_esc(note)}</div>'
        rows.append(
            f'<tr><td class="num">{p.get("score", 0):.2f}</td>'
            f'<td>{_esc(p.get("confidence", ""))}</td>'
            f'<td class="passage">{_esc(p.get("text", ""))}</td>'
            f'<td>{explanation}</td></tr>')
    coverage = ""
    if ai.get("repo_total"):
        note = labels["repo_coverage"].format(
            matched=ai.get("repo_matched", 0), total=ai["repo_total"])
        coverage = f'<p class="repo-coverage">{_esc(note)}</p>'
    return (f'<section class="ai-patterns"><h2>{_esc(labels["top_patterns"])}'
            f'</h2>{coverage}<table class="category-table">'
            f'<tr><th class="num">{_esc(labels["score"])}</th>'
            f'<th>{_esc(labels["confidence"])}</th>'
            f'<th>{_esc(labels["text"])}</th>'
            f'<th>{_esc(labels["explanation"])}</th></tr>{"".join(rows)}</table></section>')


def render_html(model: ReportModel, lang: str = "en") -> str:
    """`ReportModel` -> a complete `<html>` document, ready for a browser or
    for `report.pdf.render_pdf`.

    Always the light `Palette`: the report is paper (or a PDF standing in
    for paper), and dark-mode colours that read well on a screen are the
    wrong contrast on white — see the module docstring.
    """
    if lang not in _LABELS:
        lang = "en"
    labels = _labels(lang)
    # *With* the desktop overlay: the XAnalyze design bundle read as tokens.
    # This document used to take the plain xFormat web palette instead, on
    # the argument that a report is paper and the overlay's muted hues are a
    # screen decision. That argument was wrong twice over. The overlay is not
    # a screen tint - it is this product's palette, the one the bundle's own
    # report artboard (3h) is drawn in, down to the severity dots; and the
    # web palette's #e5484d beside the window's #c0564f meant one run showed
    # a person two different reds for one severity depending on which
    # surface they were looking at.
    palette = palettes(overlay=True)["light"]

    # Grouped, not raw: one card per distinct problem, carrying every place
    # it was found. A thirty-page crawl of a site with a shared header used
    # to print the header's every fault thirty times. See
    # `ReportModel.grouped_findings`.
    findings = model.grouped_findings()
    by_severity: dict = {}
    by_category: dict = {}
    for finding in findings:
        by_severity[finding.severity] = by_severity.get(finding.severity, 0) + 1
        by_category[finding.category] = by_category.get(finding.category, 0) + 1
    mode_label = labels["mode"].get(model.meta.mode, model.meta.mode)
    logo = _logo_data_uri()

    stat_cards = []
    for rank in range(4):
        names = [name for name, r in
                 (("critical", 0), ("high", 0), ("serious", 1), ("medium", 1),
                  ("moderate", 2), ("low", 2), ("minor", 3))
                 if r == rank]
        count = sum(by_severity.get(name, 0) for name in names)
        if count == 0 and rank not in (0,):
            continue
        label = _SEVERITY_LABEL[rank].get(lang, _SEVERITY_LABEL[rank]["en"])
        # The same four-step ramp as the chart three lines below it. These
        # were two different maps, so "serious" was orange in the bar and
        # amber in the card that counts it.
        accent = _severity_inks(palette)[rank]
        stat_cards.append(_stat_card(count, label, palette, accent))

    # One table, not four. The category counts, the AI-pattern confidence
    # bands and the character tallies were three tables in three sections
    # separated by the findings, so a reader asking "what kind of thing did
    # this find" had to hold three places at once and never saw them beside
    # each other. They answer the same question and now sit in one answer.
    what_rows = _what_was_found(model, by_category, labels)

    charts = _charts(by_severity, by_category, labels, palette, lang)
    legend = _legend(findings, labels, lang)

    findings_html = ("".join(_finding_card(f, lang, palette) for f in findings)
                     if findings else f'<p class="empty">{_esc(labels["no_findings"])}</p>')

    authwall_section = (_behind_the_login(model, labels, palette)
                        + _sharepoint_section(model, labels))
    coverage_section = ""
    if model.coverage:
        from audit.coverage import coverage_summary
        coverage_title, coverage_text = coverage_summary(model.coverage, lang)
        coverage_section = (f'<section class="authwall"><h2>{_esc(coverage_title)}</h2>'
                            f'<p class="authwall-note">{_esc(coverage_text)}</p></section>')
        from audit.vitals import performance_lines
        performance_title, lines = performance_lines(model.coverage, lang)
        if lines:
            coverage_section += (f'<section class="authwall"><h2>{_esc(performance_title)}</h2><ul>'
                                 + ''.join(f'<li>{_esc(line)}</li>' for line in lines) + '</ul></section>')
    first_section = _first_things(model, labels, palette)
    work_section = _where_the_work_is(model, labels, palette)
    pages_section = _pages_section(model, labels)
    ai_section = _top_patterns_section(model, labels, lang)
    typo_section = ""

    # The heading is the name; the target is the line under it. A report
    # headed by `/Users/…/simulations/mixed-problems` wraps to three lines,
    # is mostly somebody's home directory, and says least at exactly the
    # moment a reader is deciding what they are looking at. `display_name`
    # answers "what is this a report about"; `target` stays, verbatim,
    # underneath, where a path is readable rather than a title.
    from report.model import display_name

