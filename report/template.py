#: Rows of the pages table before it is cut short. A crawl of a large site
#: listed every page it touched - 192 numbered lines on a real run - which is
#: an index, not a finding, and it pushed the actual problems several pages
#: further back.
_PAGES_SHOWN = 40

#: Characters shown per character-tally row.
_CHAR_ROWS = 12


def _what_was_found(model: ReportModel, by_category: dict, labels: dict) -> str:
    """Every kind of thing the run found, as one table.

    Grouped by where it comes from - the audit's categories, the AI-text
    pass's confidence bands, the character pass's tallies - because those are
    three different questions being answered on one page, and a reader needs
    to see which is which. What they must not have to do is find three tables
    in three places to compare them.
    """
    # Every row says what its own number counts. The table holds two units
    # at once and cannot stop doing so - a category is a count of distinct
    # problems, a character tally is a count of occurrences - and while both
    # were unlabelled the same word carried both: "Typography 5" in this
    # table and in the chart beside it, "Typography ..." summing to 52 four
    # rows below. One name, two numbers, no way to tell which was which.
    # (P-36, XAnalyze.)
    rows = []
    for cat, count in sorted(by_category.items(), key=lambda kv: -kv[1]):
        rows.append((_esc(labels["cat"].get(cat, cat)),
                     _esc(labels["distinct"]), count))

    ai = model.ai_patterns or {}
    if ai.get("total", 0):
        for band in ("high", "medium", "low"):
            count = ai.get(band, 0)
            if count:
                rows.append((_esc(labels["ai_patterns"]),
                             _esc(labels["confidence"]) + ": " + _esc(band),
                             count))

    typo = model.typography or {}
    if typo.get("total", 0):
        # Filed under the category's own short name, not under the long
        # "Typography issues (non-keyboard characters)". Two labels that
        # both read as "typography" put one subject in two places in one
        # table; one label plus the grouping below keeps its rows together,
        # where the two numbers can be read against each other.
        group = _esc(labels["cat"].get(CATEGORY_TYPOGRAPHY,
                                       labels["typography"]))
        rows.append((group, _esc(labels["occurrences_total"]),
                     typo.get("total", 0)))
        characters = sorted((typo.get("by_character") or {}).items(),
                            key=lambda kv: -kv[1])
        for name, count in characters[:_CHAR_ROWS]:
            rows.append((group, _esc(name), count))
        rest = sum(count for _n, count in characters[_CHAR_ROWS:])
        if rest:
            rows.append((group,
                         _esc(labels["and_more"].format(
                             count=len(characters) - _CHAR_ROWS)), rest))

    if not rows:
        return ""
    # Rows of one group sit together, strongest group first. Before this the
    # category block was sorted by count and the tallies were appended after
    # it, so "Typography, distinct problems: 5" and "Typography, occurrences
    # in total: 52" could be a dozen rows apart - which is the whole reason
    # the two numbers read as a contradiction rather than as two facts.
    order: list = []
    grouped: dict = {}
    for group, detail, count in rows:
        if group not in grouped:
            grouped[group] = []
            order.append(group)
        grouped[group].append((group, detail, count))
    rows = [row for group in order for row in grouped[group]]
    body = "".join(
        f'<tr><td>{group}</td><td class="detail">{detail}</td>'
        f'<td class="num">{count}</td></tr>'
        for group, detail, count in rows)
    return (f'<table class="category-table find-table">'
            f'<tr><th>{_esc(labels["source_group"])}</th>'
            f'<th>{_esc(labels["detail"])}</th>'
            f'<th class="num">{_esc(labels["count"])}</th></tr>{body}</table>')


def _bar_chart(pairs, labels_by_key, palette, colours=None) -> str:
    """A horizontal bar chart in plain CSS.

    No script and no image: `printToPdf` is the consumer, and a chart that
    depends on either is a chart that sometimes prints blank. Widths are
    percentages of the largest bar, so the shape is readable even when the
    counts run to five digits.
    """
    pairs = [(key, value) for key, value in pairs if value]
    if not pairs:
        return ""
    top = max(value for _k, value in pairs) or 1
    rows = []
    for key, value in pairs:
        width = max(2.0, value / top * 100)
        colour = (colours or {}).get(key, palette.accent)
        rows.append(
            f'<div class="bar-row">'
            f'<span class="bar-label">{_esc(labels_by_key.get(key, key))}</span>'
            f'<span class="bar-track">'
            f'<span class="bar-fill" style="width:{width:.1f}%;'
            f'background:{colour}"></span></span>'
            f'<span class="bar-num">{value}</span></div>')
    return "".join(rows)


def _charts(by_severity: dict, by_category: dict, labels: dict, palette,
            lang: str) -> str:
    """The two charts that open the report.

    Counts in a table are exact and shapeless; a reader looking at a summary
    wants to know where the weight is before reading a number. Both are here,
    which is why the table below them is not redundant.
    """
    severity_labels, severity_colours, severity_pairs = {}, {}, []
    for rank, names in ((0, ("critical", "high")), (1, ("serious", "medium")),
                        (2, ("moderate", "low")), (3, ("minor",))):
        count = sum(by_severity.get(name, 0) for name in names)
        key = f"rank{rank}"
        severity_labels[key] = _SEVERITY_LABEL[rank].get(
            lang, _SEVERITY_LABEL[rank]["en"])
        # The palette's own four-step ramp, not `error`/`amber`/`amber`.
        # Ranks 1 and 2 were both `palette.amber`, so "serious" and
        # "moderate" drew as the same colour and a four-step chart read as
        # three - the defect the ramp exists to prevent, in the one artifact
        # whose whole job is to show where the weight is. Same four tokens
        # the window's `SeverityBar` and the TUI's summary table paint with.
        severity_colours[key] = _severity_inks(palette)[rank]
        severity_pairs.append((key, count))

    severity_bars = _bar_chart(severity_pairs, severity_labels, palette,
                               severity_colours)
    category_bars = _bar_chart(
        sorted(by_category.items(), key=lambda kv: -kv[1]),
        labels["cat"], palette)
    if not severity_bars and not category_bars:
        return ""

    blocks = []
    for title, bars in ((labels["chart_severity"], severity_bars),
                        (labels["chart_category"], category_bars)):
        if bars:
            blocks.append(f'<div class="chart"><h3>{_esc(title)}</h3>{bars}</div>')
    return f'<div class="charts">{"".join(blocks)}</div>'


def _behind_the_login(model: ReportModel, labels: dict, palette) -> str:
    """What the run did not read, because a door was in front of it.

    Placed above everything else in the document for the same reason the
    terminal prints it first: it changes what every other number means. A
    report that says "40 pages, 3 findings" over a site that answered with
    one login form forty times is not a strict report, it is a false one,
    and this is the paragraph that stops it being handed on as true.
    """
    auth = model.auth or {}
    if not auth.get("blocked"):
        return ""
    rows = "".join(
        f'<tr><td>{_esc(labels["authwall_signal"].get(row["signal"], row["signal"]))}</td>'
        f'<td class="num">{row["count"]}</td>'
        f'<td class="detail">{_esc(", ".join(row["addresses"]))}</td></tr>'
        for row in auth.get("rows", ()))
    headline = (labels["authwall_whole"] if auth.get("whole")
                else labels["authwall_some"]).format(
        blocked=auth["blocked"], pages=auth["pages"])
    return (f'<section class="authwall"><h2>{_esc(labels["authwall"])}</h2>'
            f'<p class="authwall-note">{_esc(headline)}</p>'
            f'<table class="category-table find-table">'
            f'<tr><th>{_esc(labels["authwall_col_signal"])}</th>'
            f'<th class="num">{_esc(labels["count"])}</th>'
            f'<th>{_esc(labels["authwall_col_where"])}</th></tr>'
            f'{rows}</table></section>')


